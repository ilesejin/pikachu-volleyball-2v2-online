export function translateMessage(
  value,
  language = document.documentElement.lang
) {
  const message = String(value);
  if (language !== 'zh') return message;
  if (Object.prototype.hasOwnProperty.call(ZH_MESSAGES, message))
    return ZH_MESSAGES[message];
  for (const prefix of ['Quick Match: ', 'Could not load the game: ']) {
    if (message.startsWith(prefix))
      return (
        ZH_MESSAGES[prefix] +
        translateMessage(message.slice(prefix.length), language)
      );
  }
  return message;
}

export function translate(
  english,
  korean,
  language = document.documentElement.lang
) {
  return language === 'ko' ? korean : translateMessage(english, language);
}
